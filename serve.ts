// Nest Egg — tiny static server for local testing only.
// Serves app/ at http://localhost:8080 (or --port <n>). Not part of the entry.
import { createServer } from "node:http";
import { readFile } from "node:fs/promises";
import { extname, join, normalize, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(resolve(fileURLToPath(new URL(".", import.meta.url))), "app");
const types: Record<string, string> = {
  ".html": "text/html; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".mjs": "text/javascript; charset=utf-8",
  ".json": "application/json; charset=utf-8",
  ".svg": "image/svg+xml",
  ".png": "image/png",
  ".jpg": "image/jpeg",
  ".jpeg": "image/jpeg",
};

let port = 8080;
const flagAt = process.argv.indexOf("--port");
if (flagAt >= 0 && process.argv[flagAt + 1]) {
  const parsed = Number.parseInt(process.argv[flagAt + 1], 10);
  if (Number.isFinite(parsed)) port = parsed;
}

const server = createServer(async (req, res) => {
  try {
    const url = new URL(req.url || "/", "http://localhost");
    let rel = decodeURIComponent(url.pathname);
    if (rel === "/") rel = "/index.html";
    const file = resolve(join(root, normalize(rel)));
    if (!file.startsWith(root)) {
      res.writeHead(403);
      res.end("Forbidden");
      return;
    }
    const body = await readFile(file);
    res.writeHead(200, { "content-type": types[extname(file)] || "application/octet-stream" });
    res.end(body);
  } catch {
    res.writeHead(404);
    res.end("Not found");
  }
});

server.listen(port, () => {
  console.log(`Nest Egg dev server: http://localhost:${port}/`);
});
